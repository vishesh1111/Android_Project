export function getLocalProducts(
  mainCategory: string,
  subCategory: string,
): Product[] {
  if (mainCategory === 'commercial' && subCategory === 'treadmills') {
    return COMMERCIAL_TREADMILLS;
  }
  if (mainCategory === 'domestic' && subCategory === 'treadmills') {
    return DOMESTIC_TREADMILLS;
  }
  if (mainCategory === 'domestic' && subCategory === 'elliptical-trainers') {
    return DOMESTIC_ELLIPTICALS;
  }
  if (mainCategory === 'domestic' && subCategory === 'bikes') {
    return DOMESTIC_BIKES;
  }
  if (mainCategory === 'domestic' && subCategory === 'strength-training') {
    return DOMESTIC_STRENGTH;
  }
  if (mainCategory === 'domestic' && subCategory === 'x-series') {
    return DOMESTIC_X_SERIES;
  }
  return [];
}

/**
 * Finds a single product by its id from all local product data.
 */
export function getLocalProductById(id: string): Product | undefined {
  return COMMERCIAL_TREADMILLS.find((p) => p.id === id) || DOMESTIC_TREADMILLS.find((p) => p.id === id) || DOMESTIC_ELLIPTICALS.find((p) => p.id === id) || DOMESTIC_BIKES.find((p) => p.id === id) || DOMESTIC_STRENGTH.find((p) => p.id === id) || DOMESTIC_X_SERIES.find((p) => p.id === id);
}
