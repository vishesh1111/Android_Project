export function getLocalProducts(
  mainCategory: string,
  subCategory: string,
): Product[] {
  if (mainCategory === 'commercial' && subCategory === 'treadmills') {
    return COMMERCIAL_TREADMILLS;
  }
  if (mainCategory === 'domestic' && subCategory === 'treadmills') {
    return DOMESTIC_TREADMILLS;
  }
  if (mainCategory === 'domestic' && subCategory === 'elliptical-trainers') {
    return DOMESTIC_ELLIPTICALS;
  }
  if (mainCategory === 'domestic' && subCategory === 'bikes') {
    return DOMESTIC_BIKES;
  }
  if (mainCategory === 'domestic' && subCategory === 'strength-training') {
    return DOMESTIC_STRENGTH;
  }
  if (mainCategory === 'domestic' && subCategory === 'x-series') {
    return DOMESTIC_X_SERIES;
  }
  if (mainCategory === 'commercial' && subCategory === 'elliptical-trainers') {
    return COMMERCIAL_ELLIPTICALS;
  }
  if (mainCategory === 'commercial' && subCategory === 'bikes') {
    return COMMERCIAL_BIKES;
  }
  if (mainCategory === 'commercial' && subCategory === 'air-rowers-ski') {
    return COMMERCIAL_AIR_ROWERS_SKI;
  }
  if (mainCategory === 'commercial' && subCategory === 'step-mill') {
    return COMMERCIAL_STEPMILL;
  }
  if (mainCategory === 'commercial' && subCategory === 'unique-products') {
    return COMMERCIAL_UNIQUE_PRODUCTS;
  }
  return [];
}

/**
 * Finds a single product by its id from all local product data.
 */
export function getLocalProductById(id: string): Product | undefined {
  return COMMERCIAL_TREADMILLS.find((p) => p.id === id) || DOMESTIC_TREADMILLS.find((p) => p.id === id) || DOMESTIC_ELLIPTICALS.find((p) => p.id === id) || DOMESTIC_BIKES.find((p) => p.id === id) || DOMESTIC_STRENGTH.find((p) => p.id === id) || DOMESTIC_X_SERIES.find((p) => p.id === id) || COMMERCIAL_ELLIPTICALS.find((p) => p.id === id) || COMMERCIAL_BIKES.find((p) => p.id === id) || COMMERCIAL_AIR_ROWERS_SKI.find((p) => p.id === id) || COMMERCIAL_STEPMILL.find((p) => p.id === id) || COMMERCIAL_UNIQUE_PRODUCTS.find((p) => p.id === id);
}
